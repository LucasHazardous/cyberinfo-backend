const mongoose = require('mongoose');
const user_service = require('../../src/service/user');
const article_service = require('../../src/service/article');

let tmpToken;
const tmpCategory = 1;
const tmpArticle = {
  title: 'Test article',
  content: 'This is test article generated by unit test module.',
  image: 'https://pl.wikipedia.org/wiki/Shiba#/media/Plik:Shiba_Inu.jpg',
  categoryId: tmpCategory,
};
let tmpArticleId;

beforeAll(async () => {
  await mongoose.connect(process.env.MONGO_URI);
  tmpToken = await user_service.login(
    process.env.ADMIN_USERNAME,
    process.env.ADMIN_PASSWORD
  );
});

test('Create article', async () => {
  const res = await article_service.createArticle(
    tmpArticle.title,
    tmpArticle.content,
    tmpArticle.image,
    tmpArticle.categoryId,
    tmpToken
  );

  expect(res).toBe(tmpArticle.title);
});

test('Edit article', async () => {
  const res = await article_service.createArticle(
    tmpArticle.title,
    tmpArticle.content + ' More testing.',
    tmpArticle.image,
    tmpArticle.categoryId,
    tmpToken
  );

  expect(res).toBe(tmpArticle.title);
});

test('Get article by title (and save id)', async () => {
  const res = await article_service.findArticleByTitle(tmpArticle.title);

  expect(res.title).toBeDefined();

  tmpArticleId = res._id;
});

test('Like article', async () => {
  const res = await article_service.likeArticle(tmpArticleId);

  expect(res).toBeTruthy();
});

test('Get article by id', async () => {
  const res = await article_service.findArticleById(tmpArticleId);

  expect(res.title).toBe(tmpArticle.title);
  expect(res.likes).toBe(1);
});

test('Get article with category', async () => {
  const res = await article_service.getArticlesWithCategory(tmpCategory);

  expect(res.length).toBeGreaterThanOrEqual(1);
});

test('Get newest article list', async () => {
  const res = await article_service.getNewestArticleList(0);

  expect(res.length).toBeGreaterThanOrEqual(1);
});

test('Get most liked article list', async () => {
  const res = await article_service.getMostLikedArticleList(0);

  expect(res.length).toBeGreaterThanOrEqual(1);
});

test('Search article by title', async () => {
  const res = await article_service.getSearchResults(
    tmpArticle.title.slice(0, 5),
    0
  );

  console.log(res);

  expect(res.length).toBeGreaterThanOrEqual(1);
});

test('Delete article by id', async () => {
  const res = await article_service.deleteArticle(tmpArticleId, tmpToken);

  expect(res).toBeTruthy();
});

afterAll(async () => {
  await mongoose.connection.close();
});
